def build(s):
    return TPL.format(
        name=s["name"], tagline=s["tagline"], today=TODAY,
        addr=s["addr"], addr_level=s.get("addr_level", "B"),
        nature=s["nature"], category=s["category"], tel=s["tel"],
        group=s["group"], group_level=s.get("group_level", "A"),
        ns_short=s["ns_short"], no=s["no"], ns=s["ns"],
        jr=s["jr"], jr_level=s["jr_level"],
        ns_note=s.get("ns_note", ""),
        group_body=s["group_body"].strip(),
        facts=s["facts"].strip(),
        fit_boundary=s.get("fit_boundary", "★★★★☆（四段环路围合，可逐段核对）"),
        fit_feature=s.get("fit_feature", "★★★☆☆"),
        keys="\n".join(s["keys"]),
        extra_src=s.get("extra_src", "").strip(),
        gaps="\n".join(s["gaps"]),
    )


def main():
    # 支持按批次传入数据模块：python src/gen_jianye_nsfz.py gen_jianye_nanwai_data
    import sys
    mod = sys.argv[1] if len(sys.argv) > 1 else "gen_jianye_nsfz_data"
    SCHOOLS = __import__(mod).SCHOOLS
    out = os.path.join(ROOT, "小学", "建邺区")
    os.makedirs(out, exist_ok=True)
    bad = 0
    for s in SCHOOLS:
        text = build(s)
        open(os.path.join(out, s["name"] + ".md"), "w", encoding="utf-8").write(text)
        n = len(text)
        if n < 1500:
            bad += 1
        print(f"{s['name']:<36}{n:>6} 字符{'' if n >= 1500 else '  ⚠ 偏短'}")
    print(f"\n共 {len(SCHOOLS)} 所，偏短 {bad} 处")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
