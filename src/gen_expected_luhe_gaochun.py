def write(path, district, src, rows, note):
    idx = json.load(open(os.path.join(ROOT, "index.json"), encoding="utf-8"))
    names = [x["name"] for x in idx["schools"]
             if x["district"] == district and x["level"] == "小学"]

    def match(short):
        norm = short.replace("（", "(").replace("）", ")")
        for n in names:
            n2 = n.replace("（", "(").replace("）", ")")
            key = norm.split("(")[0]
            if key and key in n2:
                return n
        return None

    out, have = [], 0
    for i, (name, ns, remark) in enumerate(rows, 1):
        hit = match(name)
        if hit:
            have += 1
        out.append([i, name, ns, remark, src, TODAY,
                    "已建档" if hit else "待补", hit or ""])
    with open(path, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["序号", "校名", "施教区要点", "备注", "来源", "采集日期",
                    "库内状态", "档案全称"])
        w.writerows(out)
    print(f"{district}：应收 {len(out)} 所，已建档 {have}，待补 {len(out)-have} → {os.path.basename(path)}")
    print(f"   注：{note}")


