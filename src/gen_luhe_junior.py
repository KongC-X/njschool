def build(s):
    return TPL.format(
        name=s["name"], tagline=s["tagline"], today=TODAY,
        addr=s["addr"], addr_level=s.get("addr_level", "A"),
        nature=s["nature"], category=s["category"],
        tel=s["tel"], no=s["no"],
        ns_short=s["ns_short"], ns_level=s["ns_level"],
        ns_policy_note=s.get("ns_policy_note", "").strip(),
        ns_body=s["ns_body"].strip(),
        feeder_short=s["feeder_short"], feeder_level=s["feeder_level"],
        feeder_body=s["feeder_body"].strip(),
        facts=s["facts"].strip(),
        zhongkao=s["zhongkao"].strip(),
        fit_boundary=s.get("fit_boundary", "★☆☆☆☆（区级文件未公布边界）"),
        fit_feature=s.get("fit_feature", "★☆☆☆☆（公开信息少）"),
        keys="\n".join(s["keys"]),
        extra_src=s.get("extra_src", "").strip(),
        gaps="\n".join(s["gaps"]),
    )


def main():
    from gen_luhe_junior_data import SCHOOLS
    out = os.path.join(ROOT, "初中", "六合区")
    os.makedirs(out, exist_ok=True)
    bad = 0
    for s in SCHOOLS:
        text = build(s)
        open(os.path.join(out, s["name"] + ".md"), "w", encoding="utf-8").write(text)
        n = len(text)
        if n < 1500:
            bad += 1
        print(f"{s['name']:<34}{n:>6} 字符{'' if n >= 1500 else '  ⚠ 偏短'}")
    print(f"\n共 {len(SCHOOLS)} 所，偏短 {bad} 处")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
