NOT_COUNTED = {"公办特教"}


def exists(stage, district, full):
    if not full:
        return False
    return os.path.isfile(os.path.join(ROOT, stage, district, full + ".md"))


def write(path, rows, stage, district, header_extra=""):
    out = os.path.join(ROOT, "data", path)
    n_ok = n_todo = n_skip = 0
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["序号", "校名", "类别", "施教区要点", "备注", "来源", "采集日期", "库内状态", "档案全称"])
        for i, (name, kind, area, full, src) in enumerate(rows, 1):
            if kind in NOT_COUNTED:
                status = "不纳入口径"
                n_skip += 1
            elif exists(stage, district, full):
                status = "已建档"
                n_ok += 1
            else:
                status = "待补"
                n_todo += 1
            w.writerow([i, name, kind, area, "", src, DATE, status, full])
    print("%-38s 共 %2d 条 | 已建档 %2d | 待补 %2d | 不纳入 %2d" % (path, len(rows), n_ok, n_todo, n_skip))
    return n_ok, n_todo


