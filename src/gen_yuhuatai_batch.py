def build(s):
    return TPL.format(
        name=s["name"], tagline=s["tagline"], today=TODAY,
        addr=s["addr"], addr_level=s.get("addr_level", "—"),
        category=s["category"], group=s["group"],
        jr=s["jr"], jr_level=s["jr_level"],
        ns=s["ns"], note=s.get("note", "").strip(),
        group_body=s["group_body"].strip(),
        jr_body=s["jr_body"].strip(),
        gaps="\n".join("- " + g for g in s["gaps"]),
        keys="\n".join(s["keys"]),
    )


def main():
    mod = "gen_yuhuatai_data"
    SCHOOLS = __import__(mod).SCHOOLS
    out = os.path.join(ROOT, "小学", "雨花台区")
    os.makedirs(out, exist_ok=True)
    bad = 0
    for s in SCHOOLS:
        text = build(s)
        open(os.path.join(out, s["name"] + ".md"), "w", encoding="utf-8").write(text)
        n = len(text)
        if n < 1500:
            bad += 1
        print(f"{s['name']:<34}{n:>6} 字符{'' if n >= 1500 else '  ⚠ 偏短'}")
    print(f"\n共 {len(SCHOOLS)} 所，偏短 {bad} 处")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
