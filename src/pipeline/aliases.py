# -*- coding: utf-8 -*-
"""俗称与组合词别名表。

解决的问题：家长的说法和档案里的写法不一致。
  - 组合词：「拉力琅」指琅琊路、拉萨路、力学三所，档案里没有哪一所叫这个
  - 俗称变体：「秦淮外校」vs「秦淮外国语」、「金中河西」vs「金陵中学河西分校」

两条设计约束，都来自已经踩过的坑：

1. 候选关键字必须至少命中 1 所真实学校，否则**构建直接失败**。
   宁可让构建报错，也不要让一条写错的别名悄悄生效。

2. 用「规范化后精确相等」匹配，不用包含匹配。
   最初写成包含匹配，「拉力琅」把琅琊路小学的明发滨江分校、柳洲东路分校
   一并算了进来，13 所里有 10 所是分校——组合词的本意是快速定位本部，
   被分校稀释后就失去意义了。

不在这里处理的两类，各有去处：
  - 阿拉伯数字写法（「29中」→ 第二十九中学）：在 schools.js 里做查询归一。
  - 地名/描述性关键词（「施教区」「九年一贯」）：只在主索引零结果时兜底搜 tagline。
"""
import re

# (别名, 规范化校名元组) —— 与 _norm(校名) 做精确相等比较
ALIASES = [
    # 鼓楼家长圈的合称
    ("拉力琅", ("琅琊路小学", "拉萨路小学", "力学小学")),
    ("拉力琅芳", ("琅琊路小学", "拉萨路小学", "力学小学", "芳草园小学")),
    ("四大名小", ("琅琊路小学", "拉萨路小学", "力学小学", "芳草园小学")),

    # 高中侧的固定组合。口径来源分两类，必须区分清楚：
    #
    #   「四大」——有档案原文佐证。中华中学档案写「与南师附中、金陵中学、
    #   南京一中并列的传统强校」，四所可逐一对应。
    #
    #   「六大」「八大」——档案中没有定义。全库 108 处提到的都是「六大名校
    #   达线率」这个升学指标，从未列出成员名单。现按站长（章老师）2026-10-31
    #   确认的口径收录，属于**运营方定义**，不是官方表述。若日后出现教育局或
    #   学校的官方口径与之冲突，以官方为准，并同步修改这里。
    #
    #   六大 = 四大 + 第二十九中学 + 第十三中学
    #   八大 = 六大 + 第九中学 + 南师附中秦淮科技高中
    ("四大名校", ("师范大学附属中学", "金陵中学", "第一中学", "中华中学")),
    ("六大", ("师范大学附属中学", "金陵中学", "第一中学", "中华中学",
              "第二十九中学", "第十三中学")),
    ("六大名校", ("师范大学附属中学", "金陵中学", "第一中学", "中华中学",
                  "第二十九中学", "第十三中学")),
    ("八大", ("师范大学附属中学", "金陵中学", "第一中学", "中华中学",
              "第二十九中学", "第十三中学", "第九中学",
              "师范大学附属中学秦淮科技高中")),
    ("八大名校", ("师范大学附属中学", "金陵中学", "第一中学", "中华中学",
                  "第二十九中学", "第十三中学", "第九中学",
                  "师范大学附属中学秦淮科技高中")),

    # 「×外校」是官方全称的缩写，与档案里的简称（秦外/玄外/郑外）写法不同
    ("秦淮外校", ("秦淮外国语学校",)),
    ("玄武外校", ("玄武外国语学校", "玄武外国语学校附属小学")),
    ("郑和外校", ("郑和外国语学校",)),

    # 校区/分校的口语顺序与官方校名相反
    ("河西南外", ("外国语学校河西初级中学",)),
    ("金中河西", ("金陵中学河西分校",)),
]

# 仍然刻意不收的组合词（列在这里，避免以后有人当成遗漏又补一遍）：
#   「附中」「一中」这类两字通用词：前者会命中所有「XX 大附中」，
#   后者与「第一中学」的阿拉伯数字归一重复，且会稀释分校结果的排序。
#   「十大」之类在「八大」之上的扩展：家长圈没有稳定共识，不预设。

# 行政区前缀，只去这一层。
# 刻意不删「附属 / 实验 / 小学 / 初中」——那套激进规范化曾把「金陵中学实验小学」
# 和「金陵中学附属小学」抹成同一所，导致 4 条错配。
RE_PREFIX = re.compile(r"^(?:江苏省)?南京(?:市)?")


def _norm(name):
    return RE_PREFIX.sub("", name).strip()


def build(schools, table=None):
    """返回 {school.id: "别名 别名"}。

    同一所学校可以命中多条别名（如琅小既有「拉力琅」又有「拉力琅芳」）。
    table 可传入自定义别名表，供单元测试用——默认走真实表，
    而真实表要求每条别名都命中至少一所学校，小样本跑不通。
    """
    by_name = {}
    for s in schools:
        by_name.setdefault(_norm(s.name), []).append(s)

    out = {}
    for alias, keys in (ALIASES if table is None else table):
        hit = 0
        for key in keys:
            for s in by_name.get(key, []):
                out.setdefault(s.id, []).append(alias)
                hit += 1
        if not hit:
            raise SystemExit(
                f"✗ 别名「{alias}」的候选校名 {keys} 在 index.json 里一所都没找到。"
                f"（别名写错会让用户搜不到，故中断构建；请核对规范化后的校名）")
    return {k: " ".join(v) for k, v in out.items()}
