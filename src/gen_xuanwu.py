def build(s):
    lv = s["level"]
    return TPL.format(
        name=s["name"], tagline=s["tagline"], today=TODAY,
        addr=s["addr"], nature=s["nature"], category=s["category"],
        tel=s["tel"], group=s["group"], group_level=s.get("group_level", "A"),
        ns_note=s["ns_note"].strip(),
        group_title=s.get("group_title", "建制与集团"),
        group_body=s["group_body"].strip(),
        timetable=TT_P if lv == "小学" else TT_J,
        facts=s["facts"].strip(),
        keys="\n".join(s["keys"]),
        level_cn=lv,
        extra_src=s.get("extra_src", "").strip(),
        gaps="\n".join("- " + g for g in s["gaps"]),
    )


def main():
    SCHOOLS = __import__("gen_xuanwu_data").SCHOOLS
    bad = 0
    for s in SCHOOLS:
        out = os.path.join(ROOT, s["level"], "玄武区")
        os.makedirs(out, exist_ok=True)
        text = build(s)
        open(os.path.join(out, s["name"] + ".md"), "w", encoding="utf-8").write(text)
        n = len(text)
        if n < 1500:
            bad += 1
        print(f"[{s['level']}] {s['name']:<32}{n:>6} 字符{'' if n >= 1500 else '  ⚠ 偏短'}")
    print(f"\n共 {len(SCHOOLS)} 所，偏短 {bad} 处")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
