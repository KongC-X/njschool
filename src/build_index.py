def build():
    items = []
    skipped = []
    for (name, short, district, level, stype, tier, tagline) in SCHOOLS:
        rel = f"{level}/{district}/{name}.md"
        abs_path = os.path.join(ROOT, rel)
        if not os.path.exists(abs_path):
            skipped.append(rel)
            continue
        items.append({
            "id": f"{level}-{district}-{name}",
            "name": name,
            "short": short,
            "district": district,
            "level": level,
            "type": stype,
            "tier": tier,
            "file": rel,
            "tagline": tagline,
            "size": os.path.getsize(abs_path),
        })

    items.sort(key=lambda x: (LEVEL_ORDER.get(x["level"], 9),
                              PRIORITY.get(x["name"], 99),
                              x["district"]))

    coverage = {lv: sum(1 for x in items if x["level"] == lv)
                for lv in ("小学", "初中", "高中")}

    doc = {
        "schema": "nanjing-school-archive/v1",
        "title": "南京中小学学校档案索引",
        "version": "2026.10",
        "updated": "2026-10-16",
        "structure": "学段/行政区/学校全称.md",
        "note": "内容层为 Markdown 文件，本索引仅提供列表与检索所需的元数据。"
                "App 渲染时读本文件取元数据，再加载对应 file 的 md 正文。",
        "coverage": coverage,
        "districts": sorted({x["district"] for x in items}),
        "fields": {
            "id": "唯一标识：学段-区-学校全称",
            "level": "小学 / 初中 / 高中",
            "type": "公办 / 民办",
            "tier": "梯队定位（民间口径，非官方排名）",
            "file": "相对仓库根目录的 md 文件路径",
            "tagline": "一句话定位，用于列表展示",
        },
        "schools": items,
    }

    out = os.path.join(ROOT, "index.json")
    with open(out, "w", encoding="utf-8") as f:
        json.dump(doc, f, ensure_ascii=False, indent=2)

    print(f"已生成：{out}")
    print(f"共 {len(items)} 所：小学 {coverage['小学']}、"
          f"初中 {coverage['初中']}、高中 {coverage['高中']}")
    print()
    for x in items:
        print(f"  [{x['level']}] {x['name']:26s} {x['district']:6s} {x['size']:>6d}B")
    if skipped:
        print()
        print("⚠️  以下条目的文件不存在，已跳过：")
        for s in skipped:
            print(f"   - {s}")


if __name__ == "__main__":
    build()
