def plain_tagline(text):
    """把 tagline 里的 Markdown 粗体标记去掉。

    index.json 的 tagline 会被原样写入四个「不解析 Markdown」的位置：
    <meta description>、og:description、JSON-LD description、列表卡片 .tag。
    若保留 ** 就会直接漏出星号（曾影响 118 个页面）。这里统一转纯文本。
    """
    return text.replace("**", "")


