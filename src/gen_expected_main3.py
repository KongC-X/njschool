# 历史改名 / 名录口径差异的显式别名（键为名录校名，值为库内档案名）
ALIAS = {
    ("小学", "建邺区", "南京市金陵河西学校（小学部）"): "金陵中学河西分校",
    # 名录写「中心小学」，库内档案用简称
    ("小学", "雨花台区", "南京市西善桥中心小学"): "南京市西善桥小学",
}

# 名录（公办施教区表）之外、但库内确实存在的民办校 → 不算缺口，也不占应收口径
OUT_OF_ROSTER = {
    # 雨花台区的「施教区表」只含公办，以下民办校未列入，库内已有档案
    ("小学", "雨花台区", "南京外国语学校雨花国际学校"),
}


def norm(s):
    """只做最小规范化：去括号学段后缀、去「南京市」前缀。

    ⚠️ 不再删除「附属 / 实验 / 中心 / 学校 / 小学 / 初中」——
    删这些词会把不同学校抹成一所，曾导致 4 条错配
    （如「金陵中学实验小学」与「金陵中学附属小学」被并成一所）。
    """
    s = s.replace("（", "(").replace("）", ")")
    s = re.sub(r"\((?:小学部|初中部|东校区小学部|东校区|小学|初中)\)$", "", s)
    s = re.sub(r"^南京(?:市)?", "", s)
    return s.replace(" ", "").replace("-", "")


def archive_names(level, district):
    d = os.path.join(ROOT, level, district)
    if not os.path.isdir(d):
        return set()
    return {f[:-3] for f in os.listdir(d) if f.endswith(".md")}


def match(name, pool, level="", district=""):
    """在库内档案名里找匹配：先别名，再精确，再规范化包含匹配。"""
    alias = ALIAS.get((level, district, name))
    if alias and alias in pool:
        return alias
    if name in pool:
        return name
    n = norm(name)
    for a in pool:
        if norm(a) == n:
            return a
    # 已取消「包含匹配」——太容易把同集团的兄弟校错配成同一所。
    # 未匹配的由人看清单后补进 ALIAS 表。
    return None


def write(fname, rows, level, district, src):
    out = os.path.join(ROOT, "data", fname)
    pool = archive_names(level, district)
    used = set()
    ok = todo = skip = 0
    detail = []
    with open(out, "w", encoding="utf-8-sig", newline="") as f:
        w = csv.writer(f)
        w.writerow(["序号", "校名", "类别", "施教区要点", "备注", "来源", "采集日期", "库内状态", "档案全称"])
        for i, (name, kind, area, tel, note) in enumerate(rows, 1):
            if kind in NOT_COUNTED or "特教" in kind:
                status, full = "不纳入口径", ""
                skip += 1
            else:
                hit = match(name, pool - used, level, district)
                if hit:
                    status, full = "已建档", hit
                    used.add(hit)
                    ok += 1
                else:
                    status, full = "待补", ""
                    todo += 1
                    detail.append(name)
            if status == "待补" and (level, district, name) in OUT_OF_ROSTER:
                status = "名录外（民办）"
                todo -= 1
                detail.pop()
            elif status == "待补" and (level, district, name) in OUT_OF_ROSTER:
                pass
            note2 = note + (f"；咨询电话 {tel}" if tel else "")
            w.writerow([i, name, kind, area, note2.strip("；"), src, DATE, status, full])
    print(f"{fname:<34} 共 {len(rows):>2} | 已建档 {ok:>2} | 待补 {todo:>2} | 不纳入 {skip:>1}")
    if todo:
        print(f"    待补明细：{detail}")
    unused = pool - used
    if unused:
        print(f"    ⚠ 库内有但名录未匹配到的档案（{len(unused)}）：{sorted(unused)}")
    return detail


