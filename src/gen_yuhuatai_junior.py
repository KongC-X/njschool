def build(s):
    return TPL.format(
        name=s["name"], tagline=s["tagline"], today=TODAY,
        addr=s["addr"], addr_level=s.get("addr_level", "—"),
        category=s["category"], group=s["group"],
        feeder=s["feeder"], feeder_level=s["feeder_level"],
        ns=s["ns"], ns_note=s.get("ns_note", ""),
        feeder_body=s["feeder_body"].strip(),
        facts=s["facts"].strip(),
        zhongkao=s.get("zhongkao", ZK_LACK).strip(),
        keys="\n".join(s["keys"]),
        extra_src=s.get("extra_src", "").strip(),
        gaps="\n".join("- " + g for g in s["gaps"]),
    )


def main():
    SCHOOLS = __import__("gen_yuhuatai_junior_data").SCHOOLS
    out = os.path.join(ROOT, "初中", "雨花台区")
    os.makedirs(out, exist_ok=True)
    bad = 0
    for s in SCHOOLS:
        text = build(s)
        open(os.path.join(out, s["name"] + ".md"), "w", encoding="utf-8").write(text)
        n = len(text)
        if n < 1500:
            bad += 1
        print(f"{s['name']:<36}{n:>6} 字符{'' if n >= 1500 else '  ⚠ 偏短'}")
    print(f"\n共 {len(SCHOOLS)} 所，偏短 {bad} 处")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
