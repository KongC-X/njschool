def build(s):
    boundary = ""
    if s.get("rows"):
        boundary = "| 边界 | 内容 |\n|---|---|\n" + "\n".join(
            f"| {a} | {b} |" for a, b in s["rows"]) + "\n"
    return TPL.format(
        name=s["name"], tagline=s["tagline"], today=TODAY,
        suffix=s.get("suffix", ""), addr=s["addr"], tel=s["tel"],
        ns_short=s.get("ns_short", "见第二节"), ns=s["ns"], entry=s["entry"],
        boundary=boundary, note=s["note"].strip(),
        fit_boundary=s.get("fit_boundary", "★★★★☆"),
        keys="\n".join(s["keys"]),
    )


def main():
    from gen_lishui_data import SCHOOLS
    os.makedirs(OUT, exist_ok=True)
    bad = 0
    for s in SCHOOLS:
        text = build(s)
        open(os.path.join(OUT, s["name"] + ".md"), "w", encoding="utf-8").write(text)
        n = len(text)
        if n < 1500:
            bad += 1
        print(f"{s['name']:<30}{n:>6} 字符{'' if n >= 1500 else '  ⚠ 偏短'}")
    print(f"\n共 {len(SCHOOLS)} 所，偏短 {bad} 处")
    return 1 if bad else 0


if __name__ == "__main__":
    raise SystemExit(main())
